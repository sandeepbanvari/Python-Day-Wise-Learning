'''
Looping Statements
    -- A loop in Python is a control structure that repeatedly executes a block of code
        as long as a specified condition is true or fixed numbers of times.
    -- Python provides two main types of loops: for loops and while loops.
    1. For loops
        -- Used when you know how many times you want to execute a block of code.
        -- Syntax:
        for variable in sequence:
            # block of code
    2. While Loops
        -- Used when you want to execute a block of code as long as a specified condition is true.
        -- Syntax:
        while condition:
            # block of code
'''
'''
Range() Function
    -- The range() function is a build-in python function used to generate a sequence of numbers.
    -- It is commonly used in for loops to repeat a block of code a specific number of times.
    Quick Reference:
    | Syntax                     | Meaning                                            |
    | -------------------------- | -------------------------------------------------- |
    | `range(stop)`              | Starts from 0, stops before `stop`                 |
    | `range(start, stop)`       | Starts from `start`, stops before `stop`           |
    | `range(start, stop, step)` | Starts from `start`, increases/decreases by `step` |
'''
