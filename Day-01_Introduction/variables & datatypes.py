'''
Data Types
    A data type defines the type of data stored in a variable, such as numbers, text, or collections of values.
    There are three main categories of data types:
    1. Primitive Data Types:
        - int: Represents whole numbers (e.g., 5, -3).
        - float: Represents decimal numbers (e.g., 3.14, -0.001).
        - str: Represents sequences of characters (e.g., "Hello", 'Python').
        - bool: Represents boolean values (True or False).
    2. Non-Primitive Data Types:
        - list: An ordered collection of items (e.g., [1, 2, 3], ["apple", "banana"]).
        - tuple: An ordered, immutable collection of items (e.g., (1, 2, 3), ("apple", "banana")).
        - set: An unordered collection of unique items (e.g., {1, 2, 3}, {"apple", "banana"}).
    3. Mapping Data Type:
        - dict: A collection of key-value pairs (e.g., {"name": "Alice", "age": 30}).
'''
