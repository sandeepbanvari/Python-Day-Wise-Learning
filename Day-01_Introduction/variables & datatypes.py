'''
What are Variables?
    variables are containers for storing data values.
    Syntax:
        identifier = data
    Variables Rules:
    1. Variables should contains alphanumeric values and use spesial char "-".
    2. Variables should not start with a number.
    3. Variables should not be a reserved keyword.
    4. Variables should not contain spaces.
    5. Variables are case-sensitive.
'''


