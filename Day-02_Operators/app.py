'''
Operators in Python
    -- Operators are going to perform between two operands.
    -- There are different types of operators in python.
        1. Arithmetic Operators
        2. Assignment Operators
        3. Comparison Operators
        4. Logical Operators
        5. Bitwise Operators    
        6. Identity Operators
        7. Membership Operators    
'''
'''
1. Arithmetic Operators
    These operators are used to perform mathematical operations between two operands.
    +, -, *, /, %, //, **
2. Assignment Operators
    These operators are used to assign values to variables.
    =, +=, -=, *=, /=, %=, //=, **=
3. Comparison Operators
    These operators are used to compare two values and return a boolean value.
    ==, !=, >, <, >=, <=
4. Logical Operators    
    These operators are used to combine two or more conditions and return a boolean value.
    and, or, not
5. Bitwise Operators
    These operators are used to perform bitwise operations on binary values.        
    &, |, ^, ~, <<, >>
6. Identity Operators
    These operators are used to compare the identity of two objects and return a boolean value.
    is, is not
7. Membership Operators
    These operators are used to check if a sequence is present in an object and return a boolean value.
    in, not in
'''
